"""2026-10 revision — turn every finished run into the paper's tables.

Reads results/revision/<run_id>/{scores.json, preds_ocp.json} and writes
results/revision/final/:

  summary.json / summary.md  every number, with its protocol
  ablation.tex               B/P/S/A x eval sets, mean +- sd over runs
  ocp_pooled.tex             OCP on the same frames for all models, 95% CI
                             from a bootstrap over recordings (R4-5)
  per_class.tex              per-class AP50/P/R on OCP (pooled) and public test
  protocol.tex               one row per reported number (R2-5, R2-12)
  counts.tex, ocp_folds.tex  data tables (R2-2, R2-7, R3-1, R4-1)
  settings.tex               training settings (R2-9)
  pr_curves.png/.pdf         PR sweep + best-F1 thresholds (R1-4)

Works with missing runs: whatever is finished gets reported, and the
missing run ids are listed at the top of summary.md.
"""
