SET_LABELS = {
    "ocp": "OCP plant (recordings unseen in training)",
    "public_test": "Public test (all three public sources)",
    "construction_test": "Construction test (Roboflow PPE)",
    "industrial_proxy": "Held-out images from training sources (SH17 + gas-mask)",
}
PAIRS = {"common": [("A", "S"), ("A", "P"), ("A", "B"), ("S", "P"), ("P", "B")],
         "all": [("A", "S"), ("A", "P"), ("S", "P")]}
METRICS = ("map50", "map50_95", "P", "R")


def _pct(x: float) -> str:
    return "n/a" if x != x else f"{100 * x:.1f}"


def _mean_sd(xs: list) -> tuple[float, float]:
    xs = [x for x in xs if x == x]
    if not xs:
        return float("nan"), float("nan")
    return statistics.fmean(xs), (statistics.stdev(xs) if len(xs) > 1 else 0.0)


def _fmt_ms(m: float, s: float, n: int) -> str:
    return _pct(m) if n <= 1 else f"{_pct(m)} $\\pm$ {_pct(s)}"


def _tex(caption: str, label: str, header: list, rows: list, colspec: str | None = None) -> str:
    colspec = colspec or "l" + "c" * (len(header) - 1)
    body = "\n".join(" & ".join(str(c) for c in r) + r" \\" for r in rows)
    return (f"% generated by ppe.collect — do not edit by hand\n"
            f"\\begin{{table}}[t]\n\\centering\n\\caption{{{caption}}}\n\\label{{{label}}}\n"
            f"\\small\n\\begin{{tabular}}{{{colspec}}}\n\\toprule\n"
            f"{' & '.join(header)} \\\\\n\\midrule\n{body}\n\\bottomrule\n"
            f"\\end{{tabular}}\n\\end{{table}}\n")


def load_scores(cfg: Config) -> dict:
    root = results_root(cfg)
    out = {}
    for run_id in all_run_ids():
        p = root / run_id / "scores.json"
        if p.is_file():
            out[run_id] = json.loads(p.read_text())
    return out


def ablation(scores: dict) -> dict:
    """exp -> eval set -> scope -> metric -> {mean, sd, n}."""
    table: dict = {}
    for exp in EXPERIMENTS:
        runs = [s for rid, s in scores.items() if rid.startswith(f"{exp}_")]
        if not runs:
            continue
        table[exp] = {}
        for name in EVAL_SETS:
            table[exp][name] = {}
            for scope in ("common", "all"):
                vals = {m: [r["sets"][name][scope][m] for r in runs] for m in METRICS}
                table[exp][name][scope] = {
                    m: dict(zip(("mean", "sd"), _mean_sd(v)), n=len(runs)) for m, v in vals.items()}
                table[exp][name][scope]["classes"] = runs[0]["sets"][name][scope]["classes"]
                table[exp][name][scope]["n_images"] = runs[0]["sets"][name][scope]["n_images"]
    return table


def pooled_ocp(cfg: Config, pool_dir: Path, scores: dict) -> dict:
    """All models on the same OCP frames. A = out-of-fold predictions of its
    5 fold models pooled; B/P/S = each seed on every frame, averaged."""
    root = results_root(cfg)
    caches: dict = {}
    for rid in scores:
        p = root / rid / "preds_ocp.json"
        if p.is_file():
            caches[rid] = json.loads(p.read_text())
    a_runs = [rid for rid in caches if rid.startswith("A_")]
    if not a_runs:
        return {}
    merged = {"images": {}}
    for rid in a_runs:
        overlap = set(merged["images"]) & set(caches[rid]["images"])
        if overlap:
            raise RuntimeError(f"A folds overlap on {sorted(overlap)[:3]} — fold split broken")
        merged["images"].update(caches[rid]["images"])
    frames = set(merged["images"])

    eval_dir = ocp_all_eval_set(cfg, pool_dir, cfg.work_root / "ocp_all")
    items = [it for it in load_eval_set(eval_dir) if it[0].name in frames]
    runs_by_exp = {"A": [merged]}
    for exp in ("B", "P", "S"):
        rs = [caches[rid] for rid in caches if rid.startswith(f"{exp}_")]
        if rs:
            runs_by_exp[exp] = rs
    scopes = scores[a_runs[0]]["scopes"]
    out = {"n_images": len(items), "a_folds": sorted(a_runs), "scopes": {}}
    for scope_name, scope in scopes.items():
        exps = [e for e in runs_by_exp if scope_name == "common" or e != "B"]
        matches = {e: [match_cache(items, c, scope) for c in runs_by_exp[e]] for e in exps}
        summaries = {e: [summarize(m, scope, cfg.op_conf) for m in matches[e]] for e in exps}
        classes = summaries["A"][0]["classes"]
        if scope_name == "all":
            out["confusion_A"] = confusion_matrix(items, merged, classes, cfg.op_conf, cfg.match_iou)
        boot = recording_bootstrap(matches, classes, cfg.n_boot, seed=0,
                                   pairs=[p for p in PAIRS[scope_name] if set(p) <= set(exps)])
        out["scopes"][scope_name] = {
            "classes": classes, "bootstrap": boot,
            "models": {e: {
                "n_runs": len(summaries[e]),
                **{m: _mean_sd([s[m] for s in summaries[e]])[0] for m in METRICS},
                "best_f1": summaries[e][0]["best_f1"] if len(summaries[e]) == 1 else {
                    k: _mean_sd([s["best_f1"][k] for s in summaries[e]])[0]
                    for k in ("conf", "P", "R", "F1")},
                "pr_curve": summaries[e][0]["pr_curve"],
                "per_class": {c: {k: _mean_sd([s["per_class"][c][k] for s in summaries[e]])[0]
                                  for k in ("n_gt", "ap50", "P", "R")}
                              for c in summaries[e][0]["per_class"]},
            } for e in exps},
        }
    if "B_s0" in caches:
        out["examples"] = pick_examples(items, merged, caches["B_s0"], scopes["all"], cfg)
    return out


def pick_examples(items: list, cache_a: dict, cache_b: dict, classes: list, cfg: Config,
                  n: int = 2) -> list:
    """Frames where A (its out-of-fold model) and B seed 0 differ most in
    correct detections at the operating point, from different recordings,
    gas-mask frames first on ties. Examples, not evidence."""
    from ppe.pool import recording_id

    ma = {m.name: m for m in match_cache(items, cache_a, classes)}
    mb = {m.name: m for m in match_cache(items, cache_b, classes)}

    def tp(m) -> int:
        return int(m.tp[m.conf >= cfg.op_conf, 0].sum())

    ranked = sorted(ma, key=lambda k: (-(tp(ma[k]) - tp(mb[k])),
                                       -ma[k].gt.get("gas_mask", 0), k))
    out, seen = [], set()
    for name in ranked:
        rec = recording_id(name)
        if rec in seen:
            continue
        seen.add(rec)
        out.append({"frame": name, "recording": rec, "tp_A": tp(ma[name]), "tp_B": tp(mb[name]),
                    "objects": sum(ma[name].gt.values())})
        if len(out) == n:
            break
    return out


def _example_figures(cfg: Config, examples: list, cache_a: dict, cache_b: dict,
                     out_dir: Path) -> None:
    """One image per example: A (left) and B (right) on the same frame,
    boxes at confidence >= op_conf."""
    from PIL import Image, ImageDraw, ImageFont, ImageOps

    try:
        font = ImageFont.load_default(size=30)
    except TypeError:  # Pillow < 10.1
        font = ImageFont.load_default()

    def panel(path: Path, entry: dict, color: tuple, title: str) -> Image.Image:
        im = ImageOps.exif_transpose(Image.open(path)).convert("RGB")
        d = ImageDraw.Draw(im)
        for (x1, y1, x2, y2), c, sc in zip(entry["xyxy"], entry["cls"], entry["conf"]):
            if sc >= cfg.op_conf:
                d.rectangle([x1, y1, x2, y2], outline=color, width=5)
                d.text((x1 + 4, max(0, y1 - 34)), f"{c} {sc:.2f}", fill=color, font=font)
        d.text((14, 10), title, fill=color, font=font)
        return im

    img_dir = cfg.work_root / "ocp_all" / "images"
    for i, ex in enumerate(examples, 1):
        path = img_dir / ex["frame"]
        left = panel(path, cache_a["images"][ex["frame"]], (0, 200, 0), "A (ours, video unseen)")
        right = panel(path, cache_b["images"][ex["frame"]], (220, 0, 0), "B (construction only)")
        both = Image.new("RGB", (left.width + right.width, left.height), "white")
        both.paste(left, (0, 0))
        both.paste(right, (left.width, 0))
        both.thumbnail((2400, 2400))
        both.save(out_dir / f"ocp_example_{i}.jpg", quality=90)


def _pr_figure(pooled: dict, out_dir: Path) -> None:
    try:
        import matplotlib
        matplotlib.use("Agg")
        import matplotlib.pyplot as plt
    except ImportError:
        print("[collect] matplotlib missing — skipping pr_curves")
        return
    scope = pooled["scopes"]["common"]  # the only scope that includes the benchmark B
    fig, ax = plt.subplots(figsize=(4.2, 3.4))
    for exp, m in scope["models"].items():
        rs = [p["R"] for p in m["pr_curve"]]
        ps = [p["P"] for p in m["pr_curve"]]
        ax.plot(rs, ps, marker=".", label=f"{exp}: {EXPERIMENTS[exp]['label']}")
        b = m["best_f1"]
        ax.scatter([b["R"]], [b["P"]], s=40, edgecolor="black", zorder=3)
    ax.set_xlabel("Recall")
    ax.set_ylabel("Precision")
    ax.set_xlim(0, 1)
    ax.set_ylim(0, 1)
    ax.set_title("OCP plant frames, common classes, confidence 0.05–0.95", fontsize=9)
    ax.legend(fontsize=7)
    fig.tight_layout()
    for ext in ("png", "pdf"):
        fig.savefig(out_dir / f"pr_curves.{ext}", dpi=200)
    plt.close(fig)


