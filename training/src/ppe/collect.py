"""2026-10 revision — turn every finished run into the paper's tables.

Reads results/revision/<run_id>/{scores.json, preds_ocp.json} and writes
results/revision/final/:

  summary.json / summary.md  every number, with its protocol
  ablation.tex               B/P/S/A x eval sets, mean +- sd over runs
  ocp_pooled.tex             OCP on the same frames for all models, 95% CI
                             from a bootstrap over recordings (R4-5)
  per_class.tex              per-class AP50/P/R on OCP (pooled) and public test
  protocol.tex               one row per reported number (R2-5, R2-12)
  counts.tex, ocp_folds.tex  data tables (R2-2, R2-7, R3-1, R4-1)
  settings.tex               training settings (R2-9)
  pr_curves.png/.pdf         PR sweep + best-F1 thresholds (R1-4)

Works with missing runs: whatever is finished gets reported, and the
missing run ids are listed at the top of summary.md.
"""
from __future__ import annotations

import json
import statistics
from pathlib import Path

import yaml

from ppe.config import CANONICAL_CLASSES, EXPERIMENTS, Config, all_run_ids
from ppe.evaluate import load_eval_set
from ppe.jobs import _write_json, protocol, results_root
from ppe.pool import EVAL_SETS, ocp_all_eval_set
from ppe.report import check_no_placeholders
from ppe.scoring import match_cache, recording_bootstrap, summarize

SET_LABELS = {
    "ocp": "OCP plant (recordings unseen in training)",
    "public_test": "Public test (all three public sources)",
    "construction_test": "Construction test (Roboflow PPE)",
    "industrial_proxy": "Held-out images from training sources (SH17 + gas-mask)",
}
PAIRS = {"common": [("A", "S"), ("A", "P"), ("A", "B"), ("S", "P"), ("P", "B")],
         "all": [("A", "S"), ("A", "P"), ("S", "P")]}
METRICS = ("map50", "map50_95", "P", "R")


def _pct(x: float) -> str:
    return "n/a" if x != x else f"{100 * x:.1f}"


def _mean_sd(xs: list) -> tuple[float, float]:
    xs = [x for x in xs if x == x]
    if not xs:
        return float("nan"), float("nan")
    return statistics.fmean(xs), (statistics.stdev(xs) if len(xs) > 1 else 0.0)


def _fmt_ms(m: float, s: float, n: int) -> str:
    return _pct(m) if n <= 1 else f"{_pct(m)} $\\pm$ {_pct(s)}"


def _tex(caption: str, label: str, header: list, rows: list, colspec: str | None = None) -> str:
    colspec = colspec or "l" + "c" * (len(header) - 1)
    body = "\n".join(" & ".join(str(c) for c in r) + r" \\" for r in rows)
    return (f"% generated by ppe.collect — do not edit by hand\n"
            f"\\begin{{table}}[t]\n\\centering\n\\caption{{{caption}}}\n\\label{{{label}}}\n"
            f"\\small\n\\begin{{tabular}}{{{colspec}}}\n\\toprule\n"
            f"{' & '.join(header)} \\\\\n\\midrule\n{body}\n\\bottomrule\n"
            f"\\end{{tabular}}\n\\end{{table}}\n")


def load_scores(cfg: Config) -> dict:
    root = results_root(cfg)
    out = {}
    for run_id in all_run_ids():
        p = root / run_id / "scores.json"
        if p.is_file():
            out[run_id] = json.loads(p.read_text())
    return out


def ablation(scores: dict) -> dict:
    """exp -> eval set -> scope -> metric -> {mean, sd, n}."""
    table: dict = {}
    for exp in EXPERIMENTS:
        runs = [s for rid, s in scores.items() if rid.startswith(f"{exp}_")]
        if not runs:
            continue
        table[exp] = {}
        for name in EVAL_SETS:
            table[exp][name] = {}
            for scope in ("common", "all"):
                vals = {m: [r["sets"][name][scope][m] for r in runs] for m in METRICS}
                table[exp][name][scope] = {
                    m: dict(zip(("mean", "sd"), _mean_sd(v)), n=len(runs)) for m, v in vals.items()}
                table[exp][name][scope]["classes"] = runs[0]["sets"][name][scope]["classes"]
                table[exp][name][scope]["n_images"] = runs[0]["sets"][name][scope]["n_images"]
    return table


def pooled_ocp(cfg: Config, pool_dir: Path, scores: dict) -> dict:
    """All models on the same OCP frames. A = out-of-fold predictions of its
    5 fold models pooled; B/P/S = each seed on every frame, averaged."""
    root = results_root(cfg)
    caches: dict = {}
    for rid in scores:
        p = root / rid / "preds_ocp.json"
        if p.is_file():
            caches[rid] = json.loads(p.read_text())
    a_runs = [rid for rid in caches if rid.startswith("A_")]
    if not a_runs:
        return {}
    merged = {"images": {}}
    for rid in a_runs:
        overlap = set(merged["images"]) & set(caches[rid]["images"])
        if overlap:
            raise RuntimeError(f"A folds overlap on {sorted(overlap)[:3]} — fold split broken")
        merged["images"].update(caches[rid]["images"])
    frames = set(merged["images"])

    eval_dir = ocp_all_eval_set(cfg, pool_dir, cfg.work_root / "ocp_all")
    items = [it for it in load_eval_set(eval_dir) if it[0].name in frames]
    runs_by_exp = {"A": [merged]}
    for exp in ("B", "P", "S"):
        rs = [caches[rid] for rid in caches if rid.startswith(f"{exp}_")]
        if rs:
            runs_by_exp[exp] = rs
    scopes = scores[a_runs[0]]["scopes"]
    out = {"n_images": len(items), "a_folds": sorted(a_runs), "scopes": {}}
    for scope_name, scope in scopes.items():
        exps = [e for e in runs_by_exp if scope_name == "common" or e != "B"]
        matches = {e: [match_cache(items, c, scope) for c in runs_by_exp[e]] for e in exps}
        summaries = {e: [summarize(m, scope, cfg.op_conf) for m in matches[e]] for e in exps}
        classes = summaries["A"][0]["classes"]
        boot = recording_bootstrap(matches, classes, cfg.n_boot, seed=0,
                                   pairs=[p for p in PAIRS[scope_name] if set(p) <= set(exps)])
        out["scopes"][scope_name] = {
            "classes": classes, "bootstrap": boot,
            "models": {e: {
                "n_runs": len(summaries[e]),
                **{m: _mean_sd([s[m] for s in summaries[e]])[0] for m in METRICS},
                "best_f1": summaries[e][0]["best_f1"] if len(summaries[e]) == 1 else {
                    k: _mean_sd([s["best_f1"][k] for s in summaries[e]])[0]
                    for k in ("conf", "P", "R", "F1")},
                "pr_curve": summaries[e][0]["pr_curve"],
                "per_class": {c: {k: _mean_sd([s["per_class"][c][k] for s in summaries[e]])[0]
                                  for k in ("n_gt", "ap50", "P", "R")}
                              for c in summaries[e][0]["per_class"]},
            } for e in exps},
        }
    return out


def _pr_figure(pooled: dict, out_dir: Path) -> None:
    try:
        import matplotlib
        matplotlib.use("Agg")
        import matplotlib.pyplot as plt
    except ImportError:
        print("[collect] matplotlib missing — skipping pr_curves")
        return
    scope = pooled["scopes"].get("all") or pooled["scopes"]["common"]
    fig, ax = plt.subplots(figsize=(4.2, 3.4))
    for exp, m in scope["models"].items():
        rs = [p["R"] for p in m["pr_curve"]]
        ps = [p["P"] for p in m["pr_curve"]]
        ax.plot(rs, ps, marker=".", label=f"{exp}: {EXPERIMENTS[exp]['label']}")
        b = m["best_f1"]
        ax.scatter([b["R"]], [b["P"]], s=40, edgecolor="black", zorder=3)
    ax.set_xlabel("Recall")
    ax.set_ylabel("Precision")
    ax.set_xlim(0, 1)
    ax.set_ylim(0, 1)
    ax.set_title("OCP plant frames, confidence sweep 0.05–0.95")
    ax.legend(fontsize=7)
    fig.tight_layout()
    for ext in ("png", "pdf"):
        fig.savefig(out_dir / f"pr_curves.{ext}", dpi=200)
    plt.close(fig)


def _settings(cfg: Config, scores: dict) -> list:
    args = None
    for rid in scores:
        p = results_root(cfg) / rid / "args.yaml"
        if p.is_file():
            args = yaml.safe_load(p.read_text())
            break
    rows = [["Detector", "YOLOv8n, COCO-pretrained (yolov8n.pt)"],
            ["Classes", f"{len(CANONICAL_CLASSES)}: " + ", ".join(CANONICAL_CLASSES)]]
    if args:
        keys = ["epochs", "patience", "imgsz", "batch", "optimizer", "lr0", "lrf", "momentum",
                "weight_decay", "warmup_epochs", "mosaic", "close_mosaic", "erasing", "fliplr",
                "hsv_h", "hsv_s", "hsv_v", "translate", "scale"]
        rows += [[k, args.get(k)] for k in keys if k in args]
    try:
        import torch
        import ultralytics
        rows += [["Ultralytics", ultralytics.__version__], ["PyTorch", torch.__version__]]
    except ImportError:
        pass
    p = protocol(cfg)
    rows += [["Eval: confidence floor (AP)", p["conf_floor"]],
             ["Eval: operating threshold (P/R)", p["op_conf"]],
             ["Eval: match IoU / NMS IoU", f"{p['match_iou']} / {p['nms_iou']}"]]
    return rows


def collect(cfg: Config, pool_dir: Path) -> Path:
    out = results_root(cfg) / "final"
    out.mkdir(parents=True, exist_ok=True)
    scores = load_scores(cfg)
    missing = [r for r in all_run_ids() if r not in scores]
    print(f"[collect] {len(scores)} finished runs; missing: {missing or 'none'}")
    counts = json.loads((Path(pool_dir) / "counts.json").read_text())
    abl = ablation(scores)
    pooled = pooled_ocp(cfg, pool_dir, scores)
    extras = {}
    for name in ("latency.json", "old_model_rescore.json"):
        p = results_root(cfg) / name
        if p.is_file():
            extras[name] = json.loads(p.read_text())
    summary = {"protocol": protocol(cfg), "missing_runs": missing, "ablation": abl,
               "ocp_pooled": pooled, "counts": counts, **extras}
    _write_json(out / "summary.json", summary)

    tex = {}
    # ablation: one row per model, columns = eval sets (common scope, mAP50)
    rows = []
    for exp, by_set in abl.items():
        row = [f"{exp} ({EXPERIMENTS[exp]['label']})"]
        for name in EVAL_SETS:
            for scope in ("common", "all"):
                if scope == "all" and exp == "B":
                    row.append("--")
                    continue
                v = by_set[name][scope]["map50"]
                row.append(_fmt_ms(v["mean"], v["sd"], v["n"]))
        rows.append(row)
    header = ["Model"] + [f"{n.replace('_', ' ')} ({s})" for n in EVAL_SETS for s in ("common", "all")]
    tex["ablation.tex"] = _tex(
        "mAP@50 (\\%), mean $\\pm$ sd over runs (A: 5 recording-grouped folds; B/P/S: 3 seeds). "
        "`common' = classes the construction baseline was trained on; `all' = all 9 classes.",
        "tab:ablation", header, rows)

    if pooled:
        rows = []
        for scope_name, sc in pooled["scopes"].items():
            boot = sc["bootstrap"]
            for exp, m in sc["models"].items():
                ci = boot["models"][exp]["ci95"]
                rows.append([scope_name, f"{exp} ({EXPERIMENTS[exp]['label']})",
                             _pct(m["map50"]), f"[{_pct(ci[0])}, {_pct(ci[1])}]",
                             _pct(m["map50_95"]), _pct(m["P"]), _pct(m["R"]),
                             f"{m['best_f1']['conf']:.2f}"])
            for pair, d in boot["pairs"].items():
                rows.append([scope_name, f"difference {pair}", _pct(d["diff"]),
                             f"[{_pct(d['ci95'][0])}, {_pct(d['ci95'][1])}]", "", "", "", ""])
        tex["ocp_pooled.tex"] = _tex(
            f"OCP plant frames ({pooled['n_images']} frames, "
            f"{next(iter(pooled['scopes'].values()))['bootstrap']['n_recordings']} recordings): "
            "all models on the same frames, 95\\% CI from a bootstrap over recordings. "
            "P/R at confidence 0.25.",
            "tab:ocp-pooled", ["Classes", "Model", "mAP@50", "95\\% CI", "mAP@50:95", "P", "R",
                               "best-F1 conf"], rows)

        sc = pooled["scopes"].get("all") or pooled["scopes"]["common"]
        a = sc["models"]["A"]["per_class"]
        pub = abl.get("A", {})
        rows = []
        for c in CANONICAL_CLASSES:
            key = c.lower().replace(" ", "_")
            o = a.get(key)
            if not o or not o["n_gt"]:
                continue
            rows.append([c, int(o["n_gt"]), _pct(o["ap50"]), _pct(o["P"]), _pct(o["R"])])
        tex["per_class.tex"] = _tex(
            "Per-class results of A on OCP plant frames (pooled out-of-fold predictions). "
            "P/R at confidence 0.25.", "tab:per-class",
            ["Class", "GT boxes", "AP@50", "P", "R"], rows)
        _pr_figure(pooled, out)

    # protocol: one row per reported number
    rows = []
    for exp, by_set in abl.items():
        for name in EVAL_SETS:
            for scope in ("common", "all"):
                if scope == "all" and exp == "B":
                    continue
                v = by_set[name][scope]
                runs = "5 folds" if exp == "A" else f"{v['map50']['n']} seeds"
                rows.append([f"ablation", exp, runs, name.replace("_", " "), v["n_images"],
                             ", ".join(v["classes"]).replace("_", "\\_"),
                             cfg.conf_floor, cfg.op_conf, cfg.match_iou])
    tex["protocol.tex"] = _tex(
        "Evaluation protocol for every reported number: checkpoint best.pt, NMS IoU "
        f"{cfg.nms_iou}, input {cfg.imgsz}px.", "tab:protocol",
        ["Table", "Model", "Runs", "Eval set", "Images", "Classes", "AP conf floor",
         "P/R conf", "Match IoU"], rows, "lllllp{4.5cm}ccc")

    rows = []
    for source, splits in counts["per_source"].items():
        for split, info in splits.items():
            if not info["images"]:
                continue
            rows.append([source.replace("_", "\\_"), split, info["images"]]
                        + [info["boxes"].get(c, 0) for c in CANONICAL_CLASSES])
    tex["counts.tex"] = _tex(
        "Images and boxes per source, split and class ('extra' = SH17 images used only by S; "
        "OCP is split by recording, see the fold table).", "tab:counts",
        ["Source", "Split", "Images"] + [c.replace("_", "\\_") for c in CANONICAL_CLASSES], rows)

    rows = []
    for f, info in counts["ocp_folds"].items():
        rows.append([f, len(info["recordings"]), info["images"]]
                    + [info["boxes"].get(c, 0) for c in CANONICAL_CLASSES if c not in
                       ("no_helmet", "no_gloves")])
    tex["ocp_folds.tex"] = _tex(
        "OCP folds: whole recordings per fold, so no recording is in both training and test.",
        "tab:ocp-folds", ["Fold", "Recordings", "Frames"]
        + [c for c in CANONICAL_CLASSES if c not in ("no_helmet", "no_gloves")], rows)

    tex["settings.tex"] = _tex("Training and evaluation settings (identical for every run).",
                               "tab:settings", ["Setting", "Value"], _settings(cfg, scores), "ll")
    for name, text in tex.items():
        (out / name).write_text(text)

    md = ["# Revision results", "", f"Missing runs: {', '.join(missing) if missing else 'none'}", ""]
    for name, text in tex.items():
        md += [f"## {name}", "", "```latex", text, "```", ""]
    for name, data in extras.items():
        md += [f"## {name}", "", "```json", json.dumps(data, indent=2), "```", ""]
    text = "\n".join(md)
    check_no_placeholders(text)
    (out / "summary.md").write_text(text)
    print(f"[collect] wrote {out}")
    return out
